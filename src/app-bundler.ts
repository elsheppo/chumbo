function sha256Hex(value: string | Uint8Array): string {
  return createHash("sha256").update(value).digest("hex");
}

async function pathExists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

export function assertAppName(name: string): string {
  const trimmed = name.trim();
  if (!APP_NAME_PATTERN.test(trimmed)) {
    throw new TypeError(
      `App name '${name}' must be lowercase kebab-case (for example 'review-queue').`,
    );
  }
  return trimmed;
}

function toTitleCase(kebab: string): string {
  return kebab
    .split("-")
    .map((part) => (part ? part[0]!.toUpperCase() + part.slice(1) : ""))
    .join(" ");
}

function toPascalCase(kebab: string): string {
  return kebab
    .split("-")
    .map((part) => (part ? part[0]!.toUpperCase() + part.slice(1) : ""))
    .join("");
}

function toCamelCase(kebab: string): string {
  const pascal = toPascalCase(kebab);
  return pascal ? pascal[0]!.toLowerCase() + pascal.slice(1) : "";
}

function toSnakeCase(kebab: string): string {
  return kebab.replaceAll("-", "_");
}

async function loadAppTemplate(name: string): Promise<string> {
  return readFile(new URL(`../templates/app/${name}`, import.meta.url), "utf8");
}

function renderTemplate(
  template: string,
  replacements: Readonly<Record<string, string>>,
): string {
  let output = template;
  for (const [key, value] of Object.entries(replacements)) {
    output = output.replaceAll(`{{${key}}}`, value);
  }
  return output;
}

async function classifyNewFile(
  path: string,
  content: string,
): Promise<PlannedFile> {
  if (!(await pathExists(path))) return { path, content, status: "create" };
  const current = await readFile(path, "utf8");
  return {
    path,
    content,
    status: current === content ? "unchanged" : "conflict",
  };
}

async function classifyGeneratedOutput(
  path: string,
  marker: string,
): Promise<PlannedBuildOutput> {
  if (!(await pathExists(path))) {
    return { path, status: "create" };
  }
  const current = await readFile(path, "utf8");
  if (current.includes(marker)) {
    return { path, status: "update" };
  }
  return {
    path,
    status: "conflict",
    reason: `Refusing to overwrite file '${path}' because it lacks the chumbo generated marker.`,
  };
}

export async function resolveAppWorkspaceLayout(options: {
  readonly cwd: string;
  readonly functionName?: string;
  readonly target?: SetupTarget;
}): Promise<AppWorkspaceLayout> {
  const functionName = options.functionName ?? "mcp";
  if (options.target) {
    const projectRoot =
      options.target === "edge-function"
        ? await findSupabaseProject(options.cwd)
        : await findPackageProject(options.cwd);
    const scaffoldDir =
      options.target === "edge-function"
        ? join(projectRoot, "supabase", "functions", functionName)
        : await hostScaffoldDirectory(
            projectRoot,
            functionName,
            options.target,
          );
    return {
      projectRoot,
      target: options.target,
      functionName,
      scaffoldDir,
      appsDir: join(scaffoldDir, "apps"),
      generatedDir: join(scaffoldDir, "generated", "apps"),
      distDir: join(scaffoldDir, "dist", "apps"),
    };
  }

  // Auto-detect: prefer Supabase Edge Function project when `supabase/config.toml` exists,
  // unless an explicit Next/Node scaffold exists in the package root.
  let packageRoot: string | undefined;
  try {
    packageRoot = await findPackageProject(options.cwd);
  } catch {
    packageRoot = undefined;
  }
  if (packageRoot) {
    const detected = await detectGeneratedScaffold(packageRoot, functionName);
    if (detected && detected.target !== "edge-function") {
      const scaffoldDir = await hostScaffoldDirectory(
        packageRoot,
        functionName,
        detected.target,
      );
      return {
        projectRoot: packageRoot,
        target: detected.target,
        functionName,
        scaffoldDir,
        appsDir: join(scaffoldDir, "apps"),
        generatedDir: join(scaffoldDir, "generated", "apps"),
        distDir: join(scaffoldDir, "dist", "apps"),
      };
    }
  }

  try {
    const supabaseRoot = await findSupabaseProject(options.cwd);
    const scaffoldDir = join(
      supabaseRoot,
      "supabase",
      "functions",
      functionName,
    );
    return {
      projectRoot: supabaseRoot,
      target: "edge-function",
      functionName,
      scaffoldDir,
      appsDir: join(scaffoldDir, "apps"),
      generatedDir: join(scaffoldDir, "generated", "apps"),
      distDir: join(scaffoldDir, "dist", "apps"),
    };
  } catch {
    if (!packageRoot) {
      throw new Error(
        "No supabase/config.toml or package.json found. Run this command inside an existing project.",
      );
    }
    const scaffoldDir = await hostScaffoldDirectory(
      packageRoot,
      functionName,
      "node",
    );
    return {
      projectRoot: packageRoot,
      target: "node",
      functionName,
      scaffoldDir,
      appsDir: join(scaffoldDir, "apps"),
      generatedDir: join(scaffoldDir, "generated", "apps"),
      distDir: join(scaffoldDir, "dist", "apps"),
    };
  }
}

async function hashDirectorySources(dir: string): Promise<string> {
  const hash = createHash("sha256");
  async function walk(current: string): Promise<void> {
    const entries = await readdir(current, { withFileTypes: true });
    entries.sort((left, right) => left.name.localeCompare(right.name));
    for (const entry of entries) {
      if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
      const fullPath = join(current, entry.name);
      if (entry.isDirectory()) {
        await walk(fullPath);
      } else if (entry.isFile()) {
        const rel = relative(dir, fullPath).replaceAll("\\", "/");
        hash.update(`file:${rel}\0`);
        hash.update(await readFile(fullPath));
        hash.update("\0");
      }
    }
  }
  await walk(dir);
  return hash.digest("hex");
}

export async function discoverProjectApps(
  layout: AppWorkspaceLayout,
): Promise<DiscoveredProjectApp[]> {
  if (!(await pathExists(layout.appsDir))) return [];
  const entries = await readdir(layout.appsDir, { withFileTypes: true });
  entries.sort((left, right) => left.name.localeCompare(right.name));
  const apps: DiscoveredProjectApp[] = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || !APP_NAME_PATTERN.test(entry.name)) continue;
    const sourceDir = join(layout.appsDir, entry.name);
    const entryHtml = join(sourceDir, "index.html");
    if (!(await pathExists(entryHtml))) continue;

    const modulePath = join(layout.generatedDir, `${entry.name}.html.ts`);
    const htmlPath = join(layout.distDir, `${entry.name}.html`);
    const sourceSha256 = await hashDirectorySources(sourceDir);
    let built = false;
    let fresh = false;
    let bytes: number | null = null;

    if (await pathExists(modulePath)) {
      built = true;
      const moduleSource = await readFile(modulePath, "utf8");
      const recordedSha = /^\/\/ source-sha256: ([a-f0-9]{64})$/mu.exec(
        moduleSource,
      )?.[1];
      fresh = recordedSha === sourceSha256;
      const recordedBytes = /^export const APP_BYTES = (\d+) as const;$/mu.exec(
        moduleSource,
      )?.[1];
      if (recordedBytes) {
        bytes = Number(recordedBytes);
      } else if (await pathExists(htmlPath)) {
        bytes = Buffer.byteLength(await readFile(htmlPath, "utf8"), "utf8");
      }
    }

    apps.push({
      name: entry.name,
      uri: `ui://${layout.functionName}/${entry.name}.html`,
      sourceDir,
      entryHtml,
      modulePath,
      htmlPath,
      sourceSha256,
      built,
      fresh,
      bytes,
    });
  }
  return apps;
}

export async function planAppAdd(options: {
  readonly cwd: string;
  readonly name: string;
  readonly functionName?: string;
  readonly target?: SetupTarget;
}): Promise<AppAddPlan> {
  const appName = assertAppName(options.name);
  const layout = await resolveAppWorkspaceLayout(options);
  const uri = `ui://${layout.functionName}/${appName}.html` as const;
  const htmlImportSpecifier =
    layout.target === "edge-function"
      ? `./generated/apps/${appName}.html.ts`
      : `./generated/apps/${appName}.html.js`;

  const replacements: Record<string, string> = {
    APP_NAME: appName,
    APP_TITLE: toTitleCase(appName),
    APP_PASCAL: toPascalCase(appName),
    APP_CAMEL: toCamelCase(appName),
    APP_SNAKE: toSnakeCase(appName),
    APP_URI: uri,
    HTML_IMPORT_SPECIFIER: htmlImportSpecifier,
  };

  const viewDir = join(layout.appsDir, appName);
  const templates = [
    ["tsconfig.json.tpl", join(layout.appsDir, "tsconfig.json")],
    ["index.html.tpl", join(viewDir, "index.html")],
    ["main.ts.tpl", join(viewDir, "main.ts")],
    ["style.css.tpl", join(viewDir, "style.css")],
    ["app-server.ts.tpl", join(layout.scaffoldDir, `${appName}-app.ts`)],
  ] as const;

  const files: PlannedFile[] = [];
  for (const [templateName, targetPath] of templates) {
    const content = renderTemplate(
      await loadAppTemplate(templateName),
      replacements,
    );
    files.push(await classifyNewFile(targetPath, content));
  }

  return {
    layout,
    appName,
    uri,
    files,
    hasConflicts: files.some((file) => file.status === "conflict"),
  };
}

export async function planAppBuild(options: {
  readonly cwd: string;
  readonly name?: string;
  readonly functionName?: string;
  readonly target?: SetupTarget;
  readonly maxBytes?: number;
}): Promise<AppBuildPlan> {
  const layout = await resolveAppWorkspaceLayout(options);
  const maxBytes = options.maxBytes ?? DEFAULT_APP_MAX_BYTES;
  if (!Number.isSafeInteger(maxBytes) || maxBytes < 1024) {
    throw new RangeError("--max-bytes must be an integer >= 1024.");
  }

  const allApps = await discoverProjectApps(layout);
  const selected = options.name
    ? allApps.filter((app) => app.name === assertAppName(options.name!))
    : allApps;

  if (options.name && selected.length === 0) {
    throw new Error(
      `No MCP App named '${options.name}' was found under ${relative(layout.projectRoot, layout.appsDir) || layout.appsDir}.`,
    );
  }

  const conflicts: string[] = [];
  const items: PlannedAppBuildItem[] = [];
  for (const app of selected) {
    const moduleStatus = await classifyGeneratedOutput(
      app.modulePath,
      GENERATED_TS_MARKER,
    );
    const htmlStatus = await classifyGeneratedOutput(
      app.htmlPath,
      GENERATED_HTML_MARKER,
    );
    for (const out of [moduleStatus, htmlStatus]) {
      if (out.status === "conflict") {
        conflicts.push(
          out.reason ??
            `Refusing to overwrite file '${out.path}' without a chumbo generated marker.`,
        );
      }
    }
    items.push({
      name: app.name,
      uri: app.uri,
      sourceDir: app.sourceDir,
      entryHtml: app.entryHtml,
      modulePath: app.modulePath,
      htmlPath: app.htmlPath,
      outputs: [moduleStatus, htmlStatus],
    });
  }

  return {
    layout,
    status: conflicts.length > 0 ? "conflict" : "planned",
    maxBytes,
    apps: items,
    conflicts,
  };
}

/** Vite plugin trimming Zod v4 locales to English-only inside any pnpm/npm/yarn virtual store. */
export function chumboZodEnglishLocalePlugin() {
  return {
    name: "chumbo-zod-english-locales",
    transform(_code: string, id: string) {
      const cleanId = id.split("?", 1)[0] ?? id;
      if (ZOD_V4_LOCALES_PATTERN.test(cleanId)) {
        return 'export { default as en } from "./en.js";';
      }
      return undefined;
    },
  };
}

/** Ensure the compiled single-file HTML contains exactly one presentation JSON placeholder. */
export function ensurePresentationPlaceholder(html: string): string {
  const first = html.indexOf(MCP_APP_PRESENTATION_PLACEHOLDER);
  if (first !== -1) {
    if (html.indexOf(MCP_APP_PRESENTATION_PLACEHOLDER, first + 1) !== -1) {
      throw new Error(
        `Compiled View HTML contains multiple ${MCP_APP_PRESENTATION_PLACEHOLDER} placeholders. Client code must not embed the placeholder literal.`,
      );
    }
    return html;
  }
  const tag = `<script id="${MCP_APP_PRESENTATION_SCRIPT_ID}" type="application/json">${MCP_APP_PRESENTATION_PLACEHOLDER}</script>`;
  if (/<\/head>/iu.test(html)) {
    return html.replace(/<\/head>/iu, `${tag}\n</head>`);
  }
  return `${tag}\n${html}`;
}

/** Audit compiled HTML for unbundled external scripts/stylesheets and byte-size budgets. */
export function auditCompiledAppHtml(
  html: string,
  maxBytes: number,
  appName: string,
): { readonly bytes: number; readonly warnings: readonly string[] } {
  if (EXTERNAL_SCRIPT_PATTERN.test(html)) {
    throw new Error(
      `Compiled MCP App '${appName}' still contains an external <script src="http..."> tag. Inline all scripts in the single-file bundle.`,
    );
  }
  if (EXTERNAL_STYLESHEET_PATTERN.test(html)) {
    throw new Error(
      `Compiled MCP App '${appName}' still contains an external stylesheet <link href="http..."> tag. Inline all styles in the single-file bundle.`,
    );
  }
  const bytes = Buffer.byteLength(html, "utf8");
  if (bytes > maxBytes) {
    throw new Error(
      `Compiled MCP App '${appName}' is ${bytes} bytes; budget is <= ${maxBytes} bytes.`,
    );
  }
  const warnings: string[] = [];
  if (bytes > ADVISORY_APP_WARN_BYTES) {
    warnings.push(
      `Bundle size is ${bytes} bytes (above ${ADVISORY_APP_WARN_BYTES}-byte advisory threshold).`,
    );
  }
  return { bytes, warnings };
}

export function stampGeneratedHtml(html: string): string {
  if (html.includes(GENERATED_HTML_MARKER)) return html;
  if (/^<!doctype\s+html>/iu.test(html)) {
    return html.replace(
      /^<!doctype\s+html>/iu,
      (match) => `${match}\n${GENERATED_HTML_MARKER}`,
    );
  }
  return `${GENERATED_HTML_MARKER}\n${html}`;
}

export function formatGeneratedTsModule(input: {
  readonly appName: string;
  readonly sourceSha256: string;
  readonly html: string;
  readonly bytes: number;
  readonly htmlSha256: string;
}): string {
  return [
    `${GENERATED_TS_MARKER} – do not edit by hand.`,
    `// source-sha256: ${input.sourceSha256}`,
    `export const APP_NAME = ${JSON.stringify(input.appName)} as const;`,
    `export const APP_BYTES = ${input.bytes} as const;`,
    `export const APP_SHA256 = ${JSON.stringify(`sha256:${input.htmlSha256}`)} as const;`,
    `export const APP_HTML = ${JSON.stringify(input.html)};`,
    "",
  ].join("\n");
}

async function resolveOptionalViteDeps(projectRoot: string): Promise<{
  readonly deps: ViteBundlerDeps | null;
  readonly missing: readonly string[];
}> {
  const missing: string[] = [];
  let viteMod: { build?: unknown } | null = null;
  let singleFileMod: { viteSingleFile?: unknown } | null = null;

  let projectRequire: NodeRequire | undefined;
  const manifestPath = join(projectRoot, "package.json");
  if (await pathExists(manifestPath)) {
    try {
      projectRequire = createRequire(manifestPath);
    } catch {
      projectRequire = undefined;
    }
  }

  try {
    if (projectRequire) {
      const resolved = projectRequire.resolve("vite");
      viteMod = (await import(pathToFileURL(resolved).href)) as {
        build?: unknown;
      };
    } else {
      viteMod = (await import("vite")) as { build?: unknown };
    }
  } catch {
    try {
      viteMod = (await import("vite")) as { build?: unknown };
    } catch {
      missing.push("vite");
    }
  }

  try {
    if (projectRequire) {
      const resolved = projectRequire.resolve("vite-plugin-singlefile");
      singleFileMod = (await import(pathToFileURL(resolved).href)) as {
        viteSingleFile?: unknown;
      };
    } else {
      singleFileMod = (await import("vite-plugin-singlefile")) as {
        viteSingleFile?: unknown;
      };
    }
  } catch {
    try {
      singleFileMod = (await import("vite-plugin-singlefile")) as {
        viteSingleFile?: unknown;
      };
    } catch {
      missing.push("vite-plugin-singlefile");
    }
  }

  if (
    missing.length > 0 ||
    typeof viteMod?.build !== "function" ||
    typeof singleFileMod?.viteSingleFile !== "function"
  ) {
    return {
      deps: null,
      missing:
        missing.length > 0 ? missing : ["vite", "vite-plugin-singlefile"],
    };
  }

  return {
    deps: {
      build: viteMod.build as ViteBundlerDeps["build"],
      viteSingleFile:
        singleFileMod.viteSingleFile as ViteBundlerDeps["viteSingleFile"],
    },
    missing: [],
  };
}

async function devInstallCommandFor(
  projectRoot: string,
  packages: readonly string[],
): Promise<string> {
  const base = await packageInstallCommand(projectRoot);
  const flag = base.startsWith("bun ") ? "-d" : "-D";
  return `${base} ${flag} ${packages.join(" ")}`;
}

export async function runAppBuild(options: {
  readonly cwd: string;
  readonly name?: string;
  readonly functionName?: string;
  readonly target?: SetupTarget;
  readonly maxBytes?: number;
  readonly check?: boolean;
  readonly resolveVite?: (
    projectRoot: string,
  ) => Promise<ViteBundlerDeps | null>;
}): Promise<AppBuildResult> {
  const plan = await planAppBuild(options);
  if (plan.status === "conflict") {
    return {
      status: "conflict",
      layout: plan.layout,
      conflicts: plan.conflicts,
      message: plan.conflicts.join(" "),
    };
  }

  if (plan.apps.length === 0) {
    return {
      status: "complete",
      layout: plan.layout,
      maxBytes: plan.maxBytes,
      apps: [],
    };
  }

  let deps: ViteBundlerDeps | null = null;
  let missing: readonly string[] = [];
  if (options.resolveVite) {
    deps = await options.resolveVite(plan.layout.projectRoot);
    if (!deps) missing = ["vite", "vite-plugin-singlefile"];
  } else {
    const resolved = await resolveOptionalViteDeps(plan.layout.projectRoot);
    deps = resolved.deps;
    missing = resolved.missing;
  }

  if (!deps) {
    const nextCommand = await devInstallCommandFor(
      plan.layout.projectRoot,
      missing,
    );
    return {
      status: "blocked",
      layout: plan.layout,
      missingDevDependencies: missing,
      nextCommand,
      message: `Missing optional dev dependencies (${missing.join(", ")}). Install them with: ${nextCommand}`,
    };
  }

  const builtApps: BuiltAppArtifact[] = [];
  const driftedFiles: string[] = [];

  for (const app of plan.apps) {
    const sourceSha256 = await hashDirectorySources(app.sourceDir);
    const out = await deps.build({
      configFile: false,
      root: app.sourceDir,
      logLevel: "silent",
      plugins: [chumboZodEnglishLocalePlugin(), deps.viteSingleFile()],
      build: {
        write: false,
        emptyOutDir: false,
        target: "es2022",
        rollupOptions: {
          input: app.entryHtml,
        },
      },
    });

    const outputs = Array.isArray(out) ? out : [out];
    let compiledHtml: string | undefined;
    for (const chunk of outputs) {
      const bundleOutputs = (
        chunk as {
          output?: Array<{
            type: string;
            fileName: string;
            source?: string | Uint8Array;
          }>;
        }
      )?.output;
      if (!Array.isArray(bundleOutputs)) continue;
      for (const item of bundleOutputs) {
        if (item.type === "asset" && item.fileName.endsWith(".html")) {
          compiledHtml =
            typeof item.source === "string"
              ? item.source
              : item.source instanceof Uint8Array
                ? new TextDecoder().decode(item.source)
                : undefined;
          break;
        }
      }
      if (compiledHtml !== undefined) break;
    }

    if (compiledHtml === undefined) {
      throw new Error(
        `Vite did not emit an HTML asset for MCP App '${app.name}'.`,
      );
    }

    const withPlaceholder = ensurePresentationPlaceholder(compiledHtml);
    const stampedHtml = stampGeneratedHtml(withPlaceholder);
    const { bytes, warnings } = auditCompiledAppHtml(
      stampedHtml,
      plan.maxBytes,
      app.name,
    );
    const htmlSha256 = sha256Hex(stampedHtml);
    const tsModule = formatGeneratedTsModule({
      appName: app.name,
      sourceSha256,
      html: stampedHtml,
      bytes,
      htmlSha256,
    });

    if (options.check) {
      const existingModule = (await pathExists(app.modulePath))
        ? await readFile(app.modulePath, "utf8")
        : null;
      const existingHtml = (await pathExists(app.htmlPath))
        ? await readFile(app.htmlPath, "utf8")
        : null;
      let drifted = false;
      if (existingModule !== tsModule) {
        drifted = true;
        driftedFiles.push(relative(plan.layout.projectRoot, app.modulePath));
      }
      if (existingHtml !== stampedHtml) {
        drifted = true;
        driftedFiles.push(relative(plan.layout.projectRoot, app.htmlPath));
      }
      builtApps.push({
        name: app.name,
        uri: app.uri,
        sourceDir: app.sourceDir,
        modulePath: app.modulePath,
        htmlPath: app.htmlPath,
        bytes,
        maxBytes: plan.maxBytes,
        sha256: `sha256:${htmlSha256}`,
        warnings,
        drifted,
      });
    } else {
      await mkdir(dirname(app.modulePath), { recursive: true });
      await mkdir(dirname(app.htmlPath), { recursive: true });
      await writeFile(app.modulePath, tsModule, "utf8");
      await writeFile(app.htmlPath, stampedHtml, "utf8");
      builtApps.push({
        name: app.name,
        uri: app.uri,
        sourceDir: app.sourceDir,
        modulePath: app.modulePath,
        htmlPath: app.htmlPath,
        bytes,
        maxBytes: plan.maxBytes,
        sha256: `sha256:${htmlSha256}`,
        warnings,
      });
    }
  }

  return {
    status: driftedFiles.length > 0 ? "drift" : "complete",
    layout: plan.layout,
    maxBytes: plan.maxBytes,
    apps: builtApps,
    ...(driftedFiles.length > 0 ? { driftedFiles } : {}),
  };
}

export async function listProjectApps(options: {
  readonly cwd: string;
  readonly functionName?: string;
  readonly target?: SetupTarget;
}): Promise<AppListReport> {
  const layout = await resolveAppWorkspaceLayout(options);
  const apps = await discoverProjectApps(layout);
  return { layout, apps };
}

function parseTargetFlag(value: string | undefined): SetupTarget | undefined {
  if (value === undefined) return undefined;
  if (!SETUP_TARGETS.includes(value as SetupTarget)) {
    throw new Error(`--target must be one of: ${SETUP_TARGETS.join(", ")}`);
  }
  return value as SetupTarget;
}

async function promptConfirm(question: string): Promise<boolean> {
  if (!process.stdin.isTTY) return false;
  const reader = createInterface({
    input: process.stdin,
    output: process.stdout,
  });
  try {
    const answer = await reader.question(`${question} [y/N] `);
    return /^y(?:es)?$/i.test(answer.trim());
  } finally {
    reader.close();
  }
}

export async function appCommand(
  rawArgs: string[],
  io: AppCommandIo = {},
): Promise<number> {
  const stdout = io.stdout ?? ((line: string) => console.log(line));
  const stderr = io.stderr ?? ((line: string) => console.error(line));
  const cwd = io.cwd ?? process.cwd();
  const isTTY = io.isTTY ?? Boolean(process.stdin.isTTY);
  const confirm = io.confirm ?? promptConfirm;

  const parsed = parseArgs({
    args: rawArgs,
    allowPositionals: true,
    strict: true,
    options: {
      function: { type: "string" },
      target: { type: "string" },
      "max-bytes": { type: "string" },
      check: { type: "boolean" },
      plan: { type: "boolean" },
      yes: { type: "boolean", short: "y" },
      json: { type: "boolean" },
      "no-config": { type: "boolean" },
      help: { type: "boolean", short: "h" },
    },
  });

  const [action, nameArg, ...extra] = parsed.positionals;
  if (parsed.values.help || !action) {
    stdout(APP_HELP);
    return 0;
  }
  if (!["add", "build", "list"].includes(action) || extra.length > 0) {
    throw new Error(
      "Use `chumbo app add <name>`, `chumbo app build [name]`, or `chumbo app list`.",
    );
  }

  const machine = parsed.values.json ?? false;
  const target = parseTargetFlag(parsed.values.target);
  const functionName = parsed.values.function ?? "mcp";
  const maxBytes =
    parsed.values["max-bytes"] !== undefined
      ? Number(parsed.values["max-bytes"])
      : DEFAULT_APP_MAX_BYTES;

  const emitJson = (value: unknown) => stdout(JSON.stringify(value, null, 2));

  if (action === "list") {
    const report = await listProjectApps({ cwd, functionName, target });
    const root = report.layout.projectRoot;
    if (machine) {
      emitJson({
        schemaVersion: 1,
        command: "app",
        action: "list",
        status: "complete",
        target: report.layout.target,
        functionName: report.layout.functionName,
        apps: report.apps.map((app) => ({
          name: app.name,
          uri: app.uri,
          sourceDir: relative(root, app.sourceDir),
          modulePath: relative(root, app.modulePath),
          built: app.built,
          fresh: app.fresh,
          bytes: app.bytes,
        })),
      });
    } else if (report.apps.length === 0) {
      stdout(
        `No MCP Apps found under ${relative(root, report.layout.appsDir)}. Run: npx chumbo app add <name>`,
      );
    } else {
      for (const app of report.apps) {
        const state = !app.built
          ? "not built"
          : app.fresh
            ? `${app.bytes ?? "?"} bytes (fresh)`
            : "stale";
        stdout(`${app.name}  ${app.uri}  [${state}]`);
      }
    }
    return 0;
  }

  if (action === "add") {
    if (!nameArg) {
      throw new Error("Usage: chumbo app add <name>");
    }
    const plan = await planAppAdd({
      cwd,
      name: nameArg,
      functionName,
      target,
    });
    const root = plan.layout.projectRoot;
    const files = plan.files.map((file) => ({
      path: relative(root, file.path),
      status: file.status,
    }));

    if (plan.hasConflicts) {
      const conflicts = files
        .filter((file) => file.status === "conflict")
        .map((file) => file.path);
      const message = `A View file already exists (${conflicts.join(", ")}). Chumbo stopped before replacing your source.`;
      if (machine) {
        emitJson({
          schemaVersion: 1,
          command: "app",
          action: "add",
          status: "conflict",
          appName: plan.appName,
          uri: plan.uri,
          target: plan.layout.target,
          functionName: plan.layout.functionName,
          files,
          message,
        });
      } else {
        stderr(message);
      }
      return 1;
    }

    if (parsed.values.plan) {
      if (machine) {
        emitJson({
          schemaVersion: 1,
          command: "app",
          action: "add",
          status: "planned",
          appName: plan.appName,
          uri: plan.uri,
          target: plan.layout.target,
          functionName: plan.layout.functionName,
          files,
          nextCommand: `npx chumbo app add ${plan.appName} --yes --json`,
        });
      } else {
        stdout(
          `File plan:\n${displayPlan(plan.files, root)}\n\nNo files changed.`,
        );
      }
      return 0;
    }

    if (machine && !parsed.values.yes) {
      emitJson({
        schemaVersion: 1,
        command: "app",
        action: "add",
        status: "needs_confirmation",
        appName: plan.appName,
        uri: plan.uri,
        target: plan.layout.target,
        functionName: plan.layout.functionName,
        files,
        nextCommand: `npx chumbo app add ${plan.appName} --yes --json`,
      });
      return 0;
    }

    if (!parsed.values.yes) {
      if (!isTTY) {
        stderr("No files changed. Re-run with --yes for non-interactive use.");
        return 1;
      }
      stdout(`File plan:\n${displayPlan(plan.files, root)}\n`);
      const approved = await confirm(`Create MCP App '${plan.appName}'?`);
      if (!approved) {
        stderr("No files changed.");
        return 1;
      }
    }

    await applyPlan(plan.files);

    if (machine) {
      emitJson({
        schemaVersion: 1,
        command: "app",
        action: "add",
        status: "complete",
        appName: plan.appName,
        uri: plan.uri,
        target: plan.layout.target,
        functionName: plan.layout.functionName,
        files,
        nextCommand: `npx chumbo app build ${plan.appName} --json`,
      });
    } else {
      stdout(`Created MCP App '${plan.appName}' (${plan.uri}).`);
      stdout(`Next: npx chumbo app build ${plan.appName}`);
    }
    return 0;
  }

  // action === "build"
  if (parsed.values.plan) {
    const plan = await planAppBuild({
      cwd,
      name: nameArg,
      functionName,
      target,
      maxBytes,
    });
    const root = plan.layout.projectRoot;
    if (machine) {
      emitJson({
        schemaVersion: 1,
        command: "app",
        action: "build",
        status: plan.status,
        target: plan.layout.target,
        functionName: plan.layout.functionName,
        maxBytes: plan.maxBytes,
        apps: plan.apps.map((app) => ({
          name: app.name,
          uri: app.uri,
          sourceDir: relative(root, app.sourceDir),
          entryHtml: relative(root, app.entryHtml),
          outputs: app.outputs.map((out) => ({
            path: relative(root, out.path),
            status: out.status,
            ...(out.reason ? { reason: out.reason } : {}),
          })),
        })),
        ...(plan.conflicts.length > 0 ? { conflicts: plan.conflicts } : {}),
        nextCommand: nameArg
          ? `npx chumbo app build ${nameArg} --json`
          : "npx chumbo app build --json",
      });
    } else if (plan.status === "conflict") {
      stderr(plan.conflicts.join("\n"));
    } else if (plan.apps.length === 0) {
      stdout("No MCP Apps found to build.");
    } else {
      for (const app of plan.apps) {
        stdout(`${app.name} (${app.uri}):`);
        for (const out of app.outputs) {
          stdout(`  ${out.status.padEnd(8)} ${relative(root, out.path)}`);
        }
      }
      stdout("No files written.");
    }
    return plan.status === "conflict" ? 1 : 0;
  }

  const result = await runAppBuild({
    cwd,
    name: nameArg,
    functionName,
    target,
    maxBytes,
    check: parsed.values.check ?? false,
    resolveVite: io.resolveVite,
  });
  const root = result.layout.projectRoot;

  if (result.status === "conflict") {
    if (machine) {
      emitJson({
        schemaVersion: 1,
        command: "app",
        action: "build",
        status: "conflict",
        target: result.layout.target,
        functionName: result.layout.functionName,
        conflicts: result.conflicts,
        message: result.message,
      });
    } else {
      stderr(result.message);
    }
    return 1;
  }

  if (result.status === "blocked") {
    if (machine) {
      emitJson({
        schemaVersion: 1,
        command: "app",
        action: "build",
        status: "blocked",
        target: result.layout.target,
        functionName: result.layout.functionName,
        missingDevDependencies: result.missingDevDependencies,
        nextCommand: result.nextCommand,
        message: result.message,
      });
    } else {
      stderr(result.message);
    }
    return 1;
  }

  if (machine) {
    emitJson({
      schemaVersion: 1,
      command: "app",
      action: "build",
      status: result.status,
      target: result.layout.target,
      functionName: result.layout.functionName,
      apps: result.apps.map((app) => ({
        name: app.name,
        uri: app.uri,
        sourceDir: relative(root, app.sourceDir),
        modulePath: relative(root, app.modulePath),
        htmlPath: relative(root, app.htmlPath),
        bytes: app.bytes,
        maxBytes: app.maxBytes,
        sha256: app.sha256,
        warnings: app.warnings,
        ...(app.drifted !== undefined ? { drifted: app.drifted } : {}),
      })),
      ...(result.driftedFiles ? { driftedFiles: result.driftedFiles } : {}),
    });
  } else if (result.status === "drift") {
    stderr(
      `MCP App build outputs are out of date (${result.driftedFiles?.join(", ")}). Run: npx chumbo app build`,
    );
  } else if (result.apps.length === 0) {
    stdout("No MCP Apps found to build.");
  } else {
    for (const app of result.apps) {
      stdout(
        `Built ${app.name}: ${relative(root, app.modulePath)} (${app.bytes} bytes, ${app.sha256})`,
      );
      for (const warning of app.warnings) {
        stderr(`Warning (${app.name}): ${warning}`);
      }
    }
  }
  return result.status === "drift" ? 1 : 0;
}
